"""
Pictures for Василий's home-screen widgets (src/modules/widgets/): for every scene a square (2×2) and a wide (4×2)
background without text — the caption is live text on the phone — and a preview with a sample caption for the
phone's widget list. Written to android/app/src/main/res/drawable-nodpi/ as WebP:
  wg_<scene>_sq.webp (480×480), wg_<scene>_wd.webp (960×480), wgp_<style>.webp (300×300, rounded, transparent corners)
Also writes each style's widget description for Android (res/xml/widget_<style>.xml, res/values/widget_strings.xml:
the name and the line from scenes.ts). A new style also needs a nested class in VasilyWidget.java and a receiver in
AndroidManifest.xml — the script stops if they are missing.
The drawing is taken from the running app («Мастерская виджетов», #/widget-lab), so the pictures always match.
Usage: pnpm dev (on :5173), then python3 scripts/media/widget_export.py
"""
import asyncio
import io
import os
import re
from pathlib import Path
from PIL import Image, ImageDraw
from playwright.async_api import async_playwright

BASE = "http://127.0.0.1:5173/"
ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "android" / "app" / "src" / "main" / "res" / "drawable-nodpi"
CHROME = os.environ.get("PW_CHROMIUM") or "/opt/pw-browsers/chromium-1194/chrome-linux/chrome"
H = 480

# Styles in gallery order, their names and lines, straight from scenes.ts.
SRC = (ROOT / "src/modules/widgets/scenes.ts").read_text(encoding="utf-8")
STYLES = re.findall(r"'(\w+)'", re.search(r"export const STYLES[^=]*= \[([^\]]+)\]", SRC).group(1))
SCENES = [s for s in STYLES if s != "live"]
META = {m[0]: (m[1], m[2]) for m in re.findall(r"(\w+)(?::| =) \{ id: '\w+'(?: as const)?, name: '([^']+)', blurb: '([^']+)'", SRC)}
META["live"] = META.pop("LIVE")
ANDROID = ROOT / "android" / "app" / "src" / "main"
PROVIDER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/media/widget_export.py from src/modules/widgets/scenes.ts. -->
<appwidget-provider xmlns:android="http://schemas.android.com/apk/res/android"
    android:description="@string/widget_{id}_about"
    android:initialLayout="@layout/widget_square"
    android:maxResizeHeight="420dp"
    android:maxResizeWidth="600dp"
    android:minHeight="110dp"
    android:minResizeHeight="100dp"
    android:minResizeWidth="100dp"
    android:minWidth="110dp"
    android:previewImage="@drawable/wgp_{id}"
    android:resizeMode="horizontal|vertical"
    android:targetCellHeight="2"
    android:targetCellWidth="2"
    android:updatePeriodMillis="0"
    android:widgetCategory="home_screen" />
"""


def xml_text(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"')


# Only these views can be inflated in a home-screen widget (classes marked @RemoteView); anything else — even a bare
# <View> — and the phone shows «Не удалось загрузить виджет».
REMOTE_VIEWS = {"FrameLayout", "LinearLayout", "RelativeLayout", "GridLayout", "ImageView", "ImageButton", "TextView", "Button",
                "ProgressBar", "ViewFlipper", "AnalogClock", "TextClock", "Chronometer", "ListView", "GridView", "StackView", "AdapterViewFlipper"}


def android_meta():
    for layout in (ANDROID / "res/layout").glob("widget_*.xml"):
        bad = sorted(set(re.findall(r"<([A-Za-z.]+)[\s>]", layout.read_text(encoding="utf-8"))) - REMOTE_VIEWS - {"?xml"})
        if bad:
            raise SystemExit(f"✖ {layout.name}: {', '.join(bad)} cannot be used in a widget (allowed: {', '.join(sorted(REMOTE_VIEWS))})")
    java = (ANDROID / "java/ru/stolypin/app/widget/VasilyWidget.java").read_text(encoding="utf-8")
    manifest = (ANDROID / "AndroidManifest.xml").read_text(encoding="utf-8")
    missing = [s for s in STYLES if f'"{s}"' not in java or f"@xml/widget_{s}\"" not in manifest]
    if missing:
        raise SystemExit(f"✖ No widget class in VasilyWidget.java or receiver in AndroidManifest.xml for: {', '.join(missing)}")
    strings = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by scripts/media/widget_export.py from src/modules/widgets/scenes.ts. -->", "<resources>"]
    for s in STYLES:
        name, blurb = META[s]
        (ANDROID / "res/xml" / f"widget_{s}.xml").write_text(PROVIDER.format(id=s), encoding="utf-8")
        label = name if s == "live" else f"Василий — {name}"
        strings += [f'    <string name="widget_{s}">{xml_text(label)}</string>', f'    <string name="widget_{s}_about">{xml_text(blurb)}</string>']
    strings.append("</resources>")
    (ANDROID / "res/values/widget_strings.xml").write_text("\n".join(strings) + "\n", encoding="utf-8")


def webp(png: bytes, path: Path, rounded=False):
    img = Image.open(io.BytesIO(png)).convert("RGBA" if rounded else "RGB")
    if rounded:  # the phone's widget list shows the preview as is: round the corners like a widget
        k = 4
        mask = Image.new("L", (img.width * k, img.height * k), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, mask.width - 1, mask.height - 1), radius=int(img.height * 0.14 * k), fill=255)
        img.putalpha(mask.resize(img.size, Image.LANCZOS))
    img.save(path, "WEBP", quality=88, method=6)
    return path.stat().st_size


async def shot(page, url: str) -> bytes:
    await page.goto(BASE + url, wait_until="networkidle")
    await page.wait_for_selector(".bare[data-ready] .scene")
    await page.evaluate("document.fonts.ready")
    await page.wait_for_timeout(300)
    await page.evaluate("document.getAnimations().forEach((a) => a.cancel())")
    return await page.locator(".bare .scene").screenshot()


async def main():
    android_meta()
    async with async_playwright() as p:
        b = await p.chromium.launch(args=["--no-sandbox"], executable_path=CHROME)
        page = await (await b.new_context(viewport={"width": 1100, "height": 700})).new_page()
        await page.goto(BASE, wait_until="networkidle")
        await page.wait_for_timeout(1200)
        if await page.locator(".tour .skip").count():  # first launch opens «Знакомство с Василием»
            await page.locator(".tour .skip").click()
        total = 0
        for s in SCENES:
            total += webp(await shot(page, f"#/widget-lab?scene={s}&shape=square&h={H}"), RES / f"wg_{s}_sq.webp")
            total += webp(await shot(page, f"#/widget-lab?scene={s}&shape=wide&h={H}"), RES / f"wg_{s}_wd.webp")
        for s in STYLES:
            total += webp(await shot(page, f"#/widget-lab?preview={s}&h=300"), RES / f"wgp_{s}.webp", rounded=True)
        await b.close()
    print(f"ok: {len(SCENES) * 2} backgrounds + {len(STYLES)} previews, {total // 1024} KB in {RES.relative_to(ROOT)}")


asyncio.run(main())
